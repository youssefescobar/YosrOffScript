// URL name: the slug without its category prefix → /fashion/casa-lila
function urlName(e) {
  const prefix = `${e.category}-`;
  return e.slug.startsWith(prefix) ? e.slug.slice(prefix.length) : e.slug;
}

export const VIDEOS = ENTRIES.map((e) => ({
  id: e.slug,
  brand: null,
  description: '',
  ...e,
  name: urlName(e),
  path: `/${e.category}/${urlName(e)}`,
  ...media(e.slug),
}));

// Categories with no videos are hidden everywhere (cards + footer filters).
export const CATEGORIES = ALL_CATEGORIES.filter((c) =>
  VIDEOS.some((v) => v.category === c.id)
).map((c) => {
  const cover = c.cover ?? VIDEOS.find((v) => v.category === c.id).poster;
  return { id: c.id, label: c.label, cover };
});

export function getVideosByCategory(categoryId) {
  return VIDEOS.filter((v) => v.category === categoryId);
}

export function getCategory(categoryId) {
  return CATEGORIES.find((c) => c.id === categoryId) || null;
}

export function getVideo(videoId) {
  return VIDEOS.find((v) => v.id === videoId) || null;
}

export function getVideoByName(categoryId, name) {
  return VIDEOS.find((v) => v.category === categoryId && v.name === name) || null;
}

/** Old #portfolio/<cat>/<n> links used the 1-based position in ENTRIES. */
export function getVideoByLegacyId(n) {
  return VIDEOS[Number(n) - 1] || null;
}

/** Tab / share title for a screen: { category?, video?, about? } */
export function pageTitle({ category = null, video = null, about = false } = {}) {
  if (about) return `About — ${SITE_NAME}`;
  if (video) return `${video.title} — ${getCategory(video.category)?.label ?? ''} · ${SITE_NAME}`;
  if (category) return `${getCategory(category)?.label ?? category} — ${SITE_NAME}`;
  return `${SITE_NAME} - Visual Storyteller`;
}
